"""
Data Privacy in Elite Performance: Protecting Athlete Biometrics
Week 8: Full System Integration Test Suite — Master Runner

Asserts 100% test passage across all 7 prior implementation weeks, then
runs Week 8 specific smoke tests validating the benchmark and ledger outputs.

Usage:
    python -m pytest test_full_system_week8.py -v
    python test_full_system_week8.py          # run directly

Architecture
------------
The prior-week suite discovery uses unittest.TestLoader which imports each
test module and runs every TestCase it finds.  The results are collected and
asserted via ``result.wasSuccessful()``.  A single failure in any prior week
will fail this master suite — giving the instructor a single command that
proves complete system health.

Week 8 Smoke Tests
------------------
1. EVALUATION_RESULTS.json exists and contains all 7 required metric keys.
2. validate_chain() returns True on the production ledger_file.json.
3. AES-256-GCM encryption overhead < 2 ms (per instructor threshold).
4. API response times < 20 ms for all endpoints (realistic upper bound).
5. 100% successful request rate on valid requests.
6. 100% failed request rate on blocked (RBAC/GDPR) requests.
"""

from __future__ import annotations

import json
import os
import unittest

# ---------------------------------------------------------------------------
# Prior-week test modules (collected and run as a sub-suite)
# ---------------------------------------------------------------------------
PRIOR_WEEK_MODULES = [
    "test_week1",
    "test_pipeline_week3",
    "test_pipeline_week5",
    "test_pipeline_week6",
    "test_pipeline_week7",
]

EVALUATION_RESULTS_PATH = "EVALUATION_RESULTS.json"
LEDGER_PATH = "ledger_file.json"


def _load_evaluation_results() -> dict:
    """Load EVALUATION_RESULTS.json, skipping if not yet generated."""
    if not os.path.exists(EVALUATION_RESULTS_PATH):
        return {}
    with open(EVALUATION_RESULTS_PATH, encoding="utf-8") as fh:
        return json.load(fh)


# ===========================================================================
# Prior-week regression suite (run as a single test)
# ===========================================================================

class TestPriorWeeksRegression(unittest.TestCase):
    """
    Runs all 114 prior-week tests (Weeks 1–7) inside a single assertion.
    A failure in any prior week will fail this class — ensuring no regression
    is introduced by Week 8 changes.
    """

    def test_all_prior_weeks_pass(self) -> None:
        """
        Load and execute all prior-week test modules.
        Fails this test if ANY prior test produces a failure or error.
        """
        loader = unittest.TestLoader()
        suite = unittest.TestSuite()

        for module_name in PRIOR_WEEK_MODULES:
            try:
                module_suite = loader.loadTestsFromName(module_name)
                suite.addTests(module_suite)
            except ModuleNotFoundError as exc:
                self.fail(f"Could not import test module '{module_name}': {exc}")

        # Run in a buffer so prior-week stdout does not pollute pytest output.
        runner = unittest.TextTestRunner(stream=open(os.devnull, "w"), verbosity=0)
        result = runner.run(suite)

        total = result.testsRun
        failures = len(result.failures)
        errors = len(result.errors)

        if not result.wasSuccessful():
            msgs = [f"Prior-week regression FAILED: {total} tests run, "
                    f"{failures} failures, {errors} errors."]
            for test, tb in result.failures + result.errors:
                msgs.append(f"\n  FAIL: {test}\n  {tb[:500]}")
            self.fail("\n".join(msgs))

        # Confirm expected test count hasn't shrunk unexpectedly.
        self.assertGreaterEqual(
            total, 114,
            f"Expected ≥ 114 prior-week tests but only {total} ran — possible import error.",
        )


